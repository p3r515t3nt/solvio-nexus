    }

    func testCalendarFormBindsVisibleMinutesAndFrozenTimezoneAcrossDST() throws {
        let parser = ISO8601DateFormatter()
        var form = TaskActionForm(now: Date(timeIntervalSince1970: 1_000), timeZone: try XCTUnwrap(TimeZone(identifier: "Europe/Berlin")))
        form.reconcileAccounts(accounts)
        form.title = "Zeitumstellung"
        form.start = try XCTUnwrap(parser.date(from: "2026-10-25T02:30:42+02:00"))
        form.end = try XCTUnwrap(parser.date(from: "2026-10-25T02:45:25+01:00"))
        let action = try form.request(accounts: accounts).actions[0]
        XCTAssertEqual(action.payload["start"], .string("2026-10-25T02:30:00+02:00"))
        XCTAssertEqual(action.payload["end"], .string("2026-10-25T02:45:00+01:00"))
        XCTAssertEqual(form.timeZoneIdentifier, "Europe/Berlin")
        let originalDefault = NSTimeZone.default
        defer { NSTimeZone.default = originalDefault }
        NSTimeZone.default = try XCTUnwrap(TimeZone(identifier: "America/New_York"))
        XCTAssertEqual(try form.request(accounts: accounts).actions[0], action)
        form.end = form.start
        XCTAssertThrowsError(try form.request(accounts: accounts))
    }

    func testMailFormCreatesOnlyExactDraftAndBindsRecipientSubjectAndBody() throws {
        var form = TaskActionForm(); form.kind = .gmail; form.mailMode = .exact; form.reconcileAccounts(accounts)
        form.recipient = "friend@example.invalid"; form.subject = "Fahrrad"; form.body = "Zeile 1\nZeile 2"
        let first = try form.request(accounts: accounts), action = first.actions[0]
        XCTAssertEqual(action.service, "gmail"); XCTAssertEqual(action.operation, "create_draft")
        XCTAssertEqual(action.target, ["mailbox": "me", "to": "friend@example.invalid", "reply_to_message": ""])
        XCTAssertEqual(action.payload["body"], .string(form.body))
        for key in ["recipient", "subject", "body"] {
            var changed = form
            if key == "recipient" { changed.recipient = "other@example.invalid" }
            if key == "subject" { changed.subject += "!" }
            if key == "body" { changed.body += "!" }
            XCTAssertNotEqual(try changed.request(accounts: accounts), first)
        }
        form.recipient += "\nBcc:other@example.invalid"
        XCTAssertThrowsError(try form.request(accounts: accounts))
    }

    func testMailCompositionDefaultsToBoundInstructionAndRecipientWithExactRetry() throws {
        var form = TaskActionForm(); form.kind = .gmail; form.reconcileAccounts(accounts)
        form.recipient = "friend@example.invalid"
        form.instruction = "Bitte freundlich nach dem Termin fragen.\nKeine Zusage erfinden. 😀"
        form.subject = "Unsichtbarer alter Betreff"; form.body = "Unsichtbarer alter Text"
        XCTAssertEqual(form.mailMode, .compose)
        let request = try form.request(accounts: accounts), action = request.actions[0]
        XCTAssertEqual(action.operation, "compose_draft")
        XCTAssertEqual(action.target, ["mailbox": "me", "to": form.recipient])
        XCTAssertEqual(action.payload, ["instruction": .string(form.instruction)])
        let body = try AppTaskBody(scope: "action", objective: form.objective, targetRepo: "",
                                   requestID: "compose-request-001", actionRequest: request)
        // Real Core request_digest with this Unicode instruction and fixed recipient.
        XCTAssertEqual(body.requestDigest, "250e44c11a6c977d3e6f12dbe12036f300a9a1089ba89e114cfca44a620deb11")
        let retry = TaskStartRetryBinding(body: body, coreID: "core", deviceID: "phone")
        XCTAssertEqual(retry.restore(scope: body.scope, objective: body.objective, targetRepo: "", coreID: "core", deviceID: "phone", actionRequest: request), body)
        for mutation in ["instruction", "recipient", "mode"] {
            var changed = form
            if mutation == "instruction" { changed.instruction += "!" }
            if mutation == "recipient" { changed.recipient = "another@example.invalid" }
            if mutation == "mode" { changed.mailMode = .exact }
            XCTAssertNil(retry.restore(scope: body.scope, objective: body.objective, targetRepo: "", coreID: "core", deviceID: "phone",
                actionRequest: try changed.request(accounts: accounts)))
        }
        XCTAssertEqual(try JSONDecoder().decode(AppTaskBody.self, from: JSONEncoder().encode(body)), body)
    }

    func testComposedMailRejectsMissingOversizedInstructionsRecipientsAndExtraFields() throws {
        var form = TaskActionForm(); form.kind = .gmail; form.reconcileAccounts(accounts)
        form.recipient = "friend@example.invalid"
        for value in ["", " \n", String(repeating: "x", count: 4001), "\u{0}"] {
            form.instruction = value; XCTAssertThrowsError(try form.request(accounts: accounts))
        }
        form.instruction = String(repeating: "x", count: 4000)
        let action = try form.request(accounts: accounts).actions[0]
        for recipient in ["", "a@example.invalid,b@example.invalid", "a@example.invalid\nBcc:b@example.invalid"] {
            form.recipient = recipient; XCTAssertThrowsError(try form.request(accounts: accounts))
        }
        XCTAssertThrowsError(try AppTaskAction(actionID: action.action_id, service: action.service, operation: action.operation,
            account: action.account, target: action.target.merging(["cc": "other@example.invalid"]) { a, _ in a }, payload: action.payload))
        XCTAssertThrowsError(try AppTaskAction(actionID: action.action_id, service: action.service, operation: action.operation,
            account: action.account, target: action.target, payload: action.payload.merging(["body": .string("Unbound text")]) { a, _ in a }))
    }

    func testDecodingRejectsExtraFieldsUnknownOperationsAndNaiveTimes() throws {
        let raw = try XCTUnwrap(JSONSerialization.jsonObject(with: JSONEncoder().encode(body())) as? [String: Any])
        for mutation in ["top", "action", "payload", "operation", "time"] {
            var changed = raw
            if mutation == "top" { changed["authority"] = true }
            else {
                var envelope = try XCTUnwrap(changed["action_request"] as? [String: Any])
                var actions = try XCTUnwrap(envelope["actions"] as? [[String: Any]])
                if mutation == "action" { actions[0]["capability"] = "unbound" }
                if mutation == "operation" { actions[0]["operation"] = "send_draft" }
                if mutation == "payload" || mutation == "time" {
                    var payload = try XCTUnwrap(actions[0]["payload"] as? [String: Any])
                    payload[mutation == "time" ? "start" : "url"] = mutation == "time" ? "2026-09-15T09:00:00" : "https://other.example"
                    actions[0]["payload"] = payload
                }
                envelope["actions"] = actions; changed["action_request"] = envelope
            }
            XCTAssertThrowsError(try JSONDecoder().decode(AppTaskBody.self, from: JSONSerialization.data(withJSONObject: changed)))
        }
    }

    @MainActor
    func testLostActionResponseRetriesExactBodyWithFreshAttestationAndRejectsChangedAction() async throws {
        let body = try body(), key = Data(repeating: 1, count: 32).base64EncodedString()
        func challenge(_ body: AppTaskBody, nonce: String) throws -> AppTaskChallenge {
            let binding: [String: Any] = ["protocol_version": 1, "type": "app_task_start_binding",
                "core_instance_id": "core-test", "principal_id": "owner-test", "device_id": "phone-test",
                "nonce": nonce, "request_digest": body.requestDigest, "enrollment_id": "enrollment-test",
                "app_attest_key_id": key, "approval_key_sha256": String(repeating: "a", count: 64)]
            let raw = try JSONSerialization.data(withJSONObject: binding, options: [.sortedKeys, .withoutEscapingSlashes])
            return AppTaskChallenge(nonce: nonce, requestDigest: body.requestDigest, expiresAt: 2_000_000_000,
                                    bindingB64: raw.base64EncodedString())
        }
        let old = try challenge(body, nonce: String(repeating: "aa", count: 32))
        let original = try action()
        let changed = try AppTaskAction(actionID: original.action_id, service: original.service,
            operation: original.operation, account: "different_account", target: original.target, payload: original.payload)
        let different = try self.body(AppTaskActionRequest(actions: [changed]))
        XCTAssertThrowsError(try old.clientDataHash(body: different, coreID: "core-test", deviceID: "phone-test",
            appAttestKeyID: key, now: 1_999_999_990))
        let attempt = TaskStartAttempt()
        var sent = [AppTaskBody](), signatures = [Data]()
        for index in 0...1 {
            do {
                _ = try await attempt.send(body: body, coreID: "core-test", deviceID: "phone-test", appAttestKeyID: key,
                    challenge: { try challenge($0, nonce: String(repeating: index == 0 ? "aa" : "bb", count: 32)) },
                    sign: { signatures.append($0); return Data([1]) },
                    submit: { task, _ in
                        sent.append(task)
                        if index == 0 { throw URLError(.networkConnectionLost) }
                        return AppTaskAccepted(taskID: "at-test", runID: "ar-test", state: "CREATED")
                    }, now: { 1_999_999_990 })
                XCTAssertEqual(index, 1)
            } catch { XCTAssertEqual(index, 0) }
        }
        XCTAssertEqual(sent, [body, body]); XCTAssertEqual(signatures.count, 2)
        XCTAssertNotEqual(signatures[0], signatures[1])
    }
