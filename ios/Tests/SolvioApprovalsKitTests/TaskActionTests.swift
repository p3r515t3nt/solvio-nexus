final class TaskActionTests: XCTestCase {
    func testAccountDisplayLabelDoesNotChangeBoundIdentityOrRequest() throws {
        let first = ActionServiceAccount(service: "gmail", account: "configured_mail", resource: "me", label: "Privat")
        let renamed = ActionServiceAccount(service: "gmail", account: "configured_mail", resource: "me", label: "Mein Konto")
        var form = TaskActionForm(); form.kind = .gmail; form.mailMode = .exact
        form.recipient = "recipient@example.invalid"; form.subject = "Betreff"; form.body = "Text"
        form.reconcileAccounts([first])
        let before = try form.request(accounts: [first])
        XCTAssertEqual(first, renamed)
        XCTAssertEqual(try form.request(accounts: [renamed]), before)
        XCTAssertEqual(try form.account(accounts: [renamed]).displayLabel, "Mein Konto")
    }
    private let accounts = [ActionServiceAccount(service: "calendar", account: "configured_account", resource: "primary"),
                            ActionServiceAccount(service: "gmail", account: "configured_mail", resource: "me")]
    private func action() throws -> AppTaskAction {
        try AppTaskAction(actionID: "calendar1", service: "calendar", operation: "create", account: "configured_account",
            target: ["calendar_id": "primary"], payload: ["summary": .string("Fahrrad \"München\" 🚲"),
                "start": .string("2026-09-15T09:00:00+02:00"), "end": .string("2026-09-15T10:00:00+02:00"),
                "all_day": .bool(false), "description": .string("Zeile 1\nZeile 2"), "location": .string("Werkstatt")])
    }
    private func request() throws -> AppTaskActionRequest { try AppTaskActionRequest(actions: [action()]) }
    private func body(_ request: AppTaskActionRequest? = nil) throws -> AppTaskBody {
        try AppTaskBody(scope: "action", objective: "Lege den Fahrradtermin für München an.", targetRepo: "",
                        requestID: "request-action-001", actionRequest: request ?? self.request())
    }

    func testNestedCanonicalHashMatchesRealPythonCoreIncludingUnicodeAndBoolean() throws {
        let body = try body()
        // Generated by real Core canonical_task_body + protocol.canonical_bytes.
        XCTAssertEqual(body.requestDigest, "88df710e55304f971f4ed118c2809a48c46364bf65a9afc41a550ba2fbd50c19")
        let encoded = try JSONEncoder().encode(body)
        XCTAssertEqual(try JSONDecoder().decode(AppTaskBody.self, from: encoded), body)
        let decoded = try XCTUnwrap(JSONSerialization.jsonObject(with: encoded) as? [String: Any])
        XCTAssertNotNil(decoded["action_request"])
        XCTAssertTrue(String(decoding: body.canonicalBytes(), as: UTF8.self).contains("\"all_day\":false"))
    }

    func testOldResearchAndBuildBodiesHaveNoActionKeyAndKeepCanonicalBytes() throws {
        for scope in ["research", "build"] {
            let body = try AppTaskBody(scope: scope, objective: "Prüfe diesen bisherigen Auftrag.", targetRepo: "", requestID: "request-old-001")
            let expected = ApprovalProtocol.canonicalBytes(["scope": .string(scope), "objective": .string(body.objective),
                "target_repo": .string(""), "client_request_id": .string(body.client_request_id)])
            XCTAssertEqual(body.canonicalBytes(), expected)
            XCTAssertFalse(String(decoding: try JSONEncoder().encode(body), as: UTF8.self).contains("action_request"))
            XCTAssertThrowsError(try AppTaskBody(scope: scope, objective: body.objective, targetRepo: "", requestID: body.client_request_id,
                                                actionRequest: request()))
        }
        XCTAssertThrowsError(try AppTaskBody(scope: "action", objective: "Erledige diesen gebundenen Auftrag.", targetRepo: "", requestID: "request-empty-001"))
    }

    func testRetryMetadataBindsEveryActionByteAndRestoresOnlyExactAction() throws {
        var draft = TaskStartDraft()
        let request = try request()
        let first = try draft.prepare(scope: "action", objective: "Erledige den gebundenen Termin.", targetRepo: "", actionRequest: request)
        let retry = TaskStartRetryBinding(body: first, coreID: "core", deviceID: "phone")
        var restarted = TaskStartDraft()
        XCTAssertEqual(try restarted.prepare(scope: first.scope, objective: first.objective, targetRepo: "", retry: retry,
            coreID: "core", deviceID: "phone", actionRequest: request), first)
        let original = try action()
        for mutation in ["account", "target", "summary", "start", "description", "location"] {
            var payload = original.payload
            if mutation == "summary" { payload[mutation] = .string("Anderer Termin") }
            if mutation == "start" { payload[mutation] = .string("2026-09-15T09:30:00+02:00") }
            if mutation == "description" || mutation == "location" { payload[mutation] = .string("Geändert") }
            let changed = try AppTaskAction(actionID: original.action_id, service: original.service, operation: original.operation,
                account: mutation == "account" ? "another_account" : original.account,
                target: mutation == "target" ? ["calendar_id": "other"] : original.target, payload: payload)
            let newRequest = try AppTaskActionRequest(actions: [changed])
            XCTAssertNil(retry.restore(scope: first.scope, objective: first.objective, targetRepo: "", coreID: "core", deviceID: "phone", actionRequest: newRequest))
            let prepared = try draft.prepare(scope: first.scope, objective: first.objective, targetRepo: "", actionRequest: newRequest)
            XCTAssertNotEqual(prepared.client_request_id, first.client_request_id)
            XCTAssertNotEqual(prepared.requestDigest, first.requestDigest)
        }
        let metadata = String(decoding: try JSONEncoder().encode(retry), as: UTF8.self)
        XCTAssertFalse(metadata.contains("Werkstatt")); XCTAssertFalse(metadata.contains("configured_account"))
    }

    func testAccountSelectionRequiresExactlyOneMeasuredServiceIdentity() throws {
        XCTAssertEqual(try ActionServiceAccount.unique(accounts, service: "calendar"), accounts[0])
        XCTAssertThrowsError(try ActionServiceAccount.unique([], service: "calendar"))
        XCTAssertThrowsError(try ActionServiceAccount.unique([accounts[0], accounts[0]], service: "calendar"))
        XCTAssertThrowsError(try ActionServiceAccount.unique([ActionServiceAccount(service: "calendar", account: "https://other.example", resource: "primary")], service: "calendar"))
        XCTAssertThrowsError(try ActionServiceAccount.unique([ActionServiceAccount(service: "gmail", account: "configured_mail", resource: "other")], service: "gmail"))
    }

    func testMultipleAccountsRequireAnOfferedExplicitChoiceAndBindItIntoRetry() throws {
        let second = ActionServiceAccount(service: "calendar", account: "work_account", resource: "work_calendar")
        let offered = accounts + [second]
        var form = TaskActionForm(); form.title = "Fahrradtermin"; form.reconcileAccounts(offered)
        XCTAssertNil(form.selectedAccount)
        XCTAssertThrowsError(try form.request(accounts: offered))
        try form.selectAccount(second, accounts: offered)
        let request = try form.request(accounts: offered)
        XCTAssertEqual(request.actions[0].account, second.account)
        XCTAssertEqual(request.actions[0].target, ["calendar_id": second.resource])
        let first = try AppTaskBody(scope: "action", objective: form.objective, targetRepo: "", requestID: "chosen-account-001", actionRequest: request)
        let retry = TaskStartRetryBinding(body: first, coreID: "core", deviceID: "phone")
        try form.selectAccount(accounts[0], accounts: offered)
        XCTAssertNil(retry.restore(scope: "action", objective: form.objective, targetRepo: "", coreID: "core", deviceID: "phone",
                                   actionRequest: try form.request(accounts: offered)))
        try form.selectAccount(second, accounts: offered)
        XCTAssertEqual(retry.restore(scope: "action", objective: form.objective, targetRepo: "", coreID: "core", deviceID: "phone",
                                     actionRequest: try form.request(accounts: offered)), first)
        let forged = ActionServiceAccount(service: "calendar", account: second.account, resource: "unoffered_calendar")
        XCTAssertThrowsError(try form.selectAccount(forged, accounts: offered))
        XCTAssertThrowsError(try form.selectAccount(accounts[1], accounts: offered))
        XCTAssertEqual(form.selectedAccount, second)
    }

    func testDisappearedSingletonKeepsItsBindingUntilExplicitReplacement() throws {
        var form = TaskActionForm(); form.title = "Fahrradtermin"; form.reconcileAccounts(accounts)
        let original = try form.request(accounts: accounts)
        let replacement = ActionServiceAccount(service: "calendar", account: accounts[0].account, resource: "changed_calendar")
        for offered in [[], [replacement], [replacement, accounts[1]]] {
            form.reconcileAccounts(offered)
            XCTAssertEqual(form.selectedAccount, accounts[0])
            XCTAssertThrowsError(try form.request(accounts: offered)) { error in
                XCTAssertEqual(error as? TaskActionError, .selectedAccountUnavailable)
            }
        }
        form.reconcileAccounts(accounts)
        XCTAssertEqual(try form.request(accounts: accounts), original)
        form.reconcileAccounts([replacement])
        try form.selectAccount(replacement, accounts: [replacement])
        XCTAssertEqual(try form.request(accounts: [replacement]).actions[0].target, ["calendar_id": "changed_calendar"])
        XCTAssertNotEqual(try form.request(accounts: [replacement]), original)
    }

    func testServiceSwitchKeepsSeparateChoicesAndCannotReuseForeignResource() throws {
        let extraMail = ActionServiceAccount(service: "gmail", account: "work_mail", resource: "me")
